        <div>
            <dt class="font-medium">## Zwischenüberschrift</dt>
            <dd class="text-gray-500 dark:text-gray-400">
                Zwei Rauten und ein Leerzeichen. Gliedert den Text und hilft bei Google.
                Ein Beitrag ohne Zwischenüberschriften ist ab etwa drei Absätzen anstrengend.
                Der Titel oben ist schon die erste Überschrift – im Text also nie mit einer Raute anfangen.
            </dd>
        </div>

        <div>
            <dt class="font-medium">**fett** und *kursiv*</dt>
            <dd class="text-gray-500 dark:text-gray-400">
                Sparsam. Wenn alles wichtig ist, ist nichts wichtig.
            </dd>
        </div>

        <div>
            <dt class="font-medium">- Aufzählung</dt>
            <dd class="text-gray-500 dark:text-gray-400">
                Bindestrich, Leerzeichen, Text. Immer dann, wenn im Fließtext ein „und dann und dann“ entsteht.
            </dd>
        </div>

        <div>
            <dt class="font-medium">[Text](https://beispiel.de)</dt>
            <dd class="text-gray-500 dark:text-gray-400">
                Verlinken. Für Links, auf die es wirklich ankommt, gibt es unten den Abschnitt
                „Weiterführende Links“ – die stehen dann als Knöpfe am Textende.
            </dd>
        </div>

        <div>
            <dt class="font-medium">&gt; Zitat</dt>
            <dd class="text-gray-500 dark:text-gray-400">
                Für Aussagen von anderen. Nicht als Stilmittel für eigene Sätze.
            </dd>
        </div>

        <div>
            <dt class="font-medium">Leerzeile = neuer Absatz</dt>
            <dd class="text-gray-500 dark:text-gray-400">
                Ein einfacher Zeilenumbruch reicht nicht. Absätze dürfen ruhig kurz sein.
            </dd>
        </div>
    </dl>

    <div class="rounded-lg bg-gray-50 p-4 dark:bg-white/5">
        <p class="font-medium">Zwei Hausregeln</p>
        <ul class="mt-2 list-disc space-y-1 pl-5 text-gray-500 dark:text-gray-400">
            <li>
                <span class="text-gray-700 dark:text-gray-300">Keine Emojis als Deko</span> –
                nicht im Titel, nicht in Zwischenüberschriften, nicht als Aufzählungszeichen.
                In einem eigenen Satz, wo sie zur Stimme gehören, sind sie in Ordnung.
                Der Titel landet in Google und beim Teilen; dort haben sie nichts verloren.
            </li>
            <li>
                <span class="text-gray-700 dark:text-gray-300">Schreib, wie du redest</span> –
                Du-Ansprache, kurze Sätze. Das ist der Unterschied zu jeder Agenturseite,
                und der einzige, den niemand kopieren kann.
            </li>
        </ul>
